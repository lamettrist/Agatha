"""Add teacher-simulated landings/resting contacts; retain original ghost cases."""
import argparse,json,sys,time
from pathlib import Path
sys.path.insert(0,str(Path(__file__).resolve().parents[1]))
import numpy as np
import pybullet as p
from agatha.schema import Scene,SceneObject,Support,Push,Tilt
from prepare_ab_data import episode


def contact_case(rng: np.random.Generator,kind: str) -> tuple[Scene,list]:
    w=float(rng.uniform(1.,1.5));d=float(rng.uniform(.7,1.0));h=float(rng.uniform(.6,.9))
    mass=float(rng.uniform(.15,1.2));rotation=(0.,0.,0.);actions=[]
    if kind=='landing_toss':
        size=(float(rng.uniform(.06,.10)),float(rng.uniform(.18,.30)),float(rng.uniform(.06,.10)));label='bottle'
    elif kind=='rest':
        label,prior=[('cell phone',(.075,.009,.15)),('laptop',(.33,.025,.23)),('cup',(.085,.11,.085)),('book',(.20,.035,.14))][int(rng.integers(4))]
        size=tuple(np.asarray(prior)*rng.uniform(.85,1.15,3))
    else:
        label='box';size=tuple(rng.uniform([.07,.025,.07],[.22,.22,.22]))
        if kind=='drop':rotation=tuple(rng.uniform([-.75,-np.pi,-.75],[.75,np.pi,.75]))
    x=float(rng.uniform(-w*.15,w*.15));z=float(rng.uniform(-d*.15,d*.15))
    extent=np.abs(np.array(p.getMatrixFromQuaternion(p.getQuaternionFromEuler(rotation))).reshape(3,3))@np.array(size)/2
    y=h+extent[1]
    if kind=='drop':y+=float(rng.uniform(.05,.6))
    if kind=='edge':x=w/2-size[0]/2-float(rng.uniform(-.02,.04))
    obj=SceneObject(id='contact',label=label,size=size,position=(x,y,z),rotation_euler=rotation,mass_kg=mass,friction=float(rng.uniform(.3,.8)))
    scene=Scene(objects=[obj],support=Support(size=(w,d),height=h))
    if kind=='landing_toss':
        direction=(float(rng.uniform(-.12,.12)),1.,float(rng.uniform(-.12,.12)))
        actions=[Push(type='push',id=obj.id,direction=direction,impulse_Ns=float(rng.uniform(2,4.5))*mass)]
    elif kind=='drop' and rng.random()<.5:
        actions=[Push(type='push',id=obj.id,direction=(0,-1,0),impulse_Ns=float(rng.uniform(.1,1.5))*mass)]
    elif kind=='edge':actions=[Push(type='push',id=obj.id,direction=(1,0),impulse_Ns=float(rng.uniform(.05,.6))*mass)]
    elif kind=='rest' and rng.random()<.25:
        angle=float(rng.uniform(-10,10));tilt=(0,0,np.radians(angle))
        r=np.array(p.getMatrixFromQuaternion(p.getQuaternionFromEuler(tilt))).reshape(3,3)
        obj.rotation_euler=tilt;obj.position=tuple(np.array([0,h-.04,0])+r@np.array([x,.04+size[1]/2,z]))
        actions=[Tilt(type='tilt_support',axis='z',angle_deg=angle)]
    return scene,actions


def main():
    parser=argparse.ArgumentParser();parser.add_argument('--source',type=Path,default=Path('data/ab_episodes.npz'));parser.add_argument('--output',type=Path,default=Path('data/contact_episodes.npz'))
    args=parser.parse_args();start=time.perf_counter();file=np.load(args.source)
    keys=('states','props','context','mask');data={key:file[key] for key in keys};old_kinds=file['kinds']
    rng=np.random.default_rng(773316);kinds=np.array(['landing_toss']*500+['drop']*400+['rest']*400+['edge']*200);rng.shuffle(kinds)
    extra={key:[] for key in keys}
    for i,kind in enumerate(kinds):
        scene,actions=contact_case(rng,str(kind))
        for key,value in zip(keys,episode(scene,actions)):extra[key].append(value)
        if (i+1)%150==0:print(f'contact episodes {i+1}/{len(kinds)}, {time.perf_counter()-start:.1f}s',flush=True)
    merged={key:np.concatenate((data[key],np.stack(extra[key]))) for key in keys};merged['kinds']=np.concatenate((old_kinds,kinds))
    args.output.parent.mkdir(parents=True,exist_ok=True);np.savez_compressed(args.output,**merged)
    metadata=dict(base_dataset=json.loads(args.source.with_suffix('.json').read_text()),new_contact_scenes=len(kinds),total_scenes=len(merged['states']),
        scene_transitions=len(merged['states'])*60,seed=773316,kinds={str(k):int((kinds==k).sum()) for k in np.unique(kinds)},
        seconds=time.perf_counter()-start,split='scene index % 10 == 0 validation; added kinds shuffled before assigning scene indices',
        note='All added trajectories generated by PyBullet. Existing disabled-table data retained. No inference collision projection added.')
    args.output.with_suffix('.json').write_text(json.dumps(metadata,indent=2));print(json.dumps(metadata,indent=2))
if __name__=='__main__':main()
